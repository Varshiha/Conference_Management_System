package com.conferences.model;

public class User 
{
    private int id;
    private String fullName;
    private String email;
    private String password;
    private int age;
    //like admin or participant
    private String role;

    public User()
    {
        //the default constructor
    }

    //constructor to fetch existing user hence the ID in it
    public User(int id,String fullName,String email,String password,int age,String role)
    {
        this.id=id;
        this.fullName=fullName;
        this.email=email;
        this.password=password;
        this.age=age;
        this.role=role;
    }

    //the constructor to create a new user hence no ID in it because the ID is autogenerated by the database
    public User(String fullName,String email,String password,int age,String role)
    {
        this.fullName=fullName;
        this.email=email;
        this.password=password;
        this.age=age;
        this.role=role;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }
    public void setEmail(String email) {
        this.email = email;
    }
    public String getPassword() {
        return password;
    }
    public void setPassword(String password) {
        this.password = password;
    }

    public int getAge() {
        return age;
    }
    public void setAge(int age) {
        this.age = age;
    }

    public String getRole() {
        return role;
    }
    public void setRole(String role) {
        this.role = role;
    }

    
    
}
